"""generate_data.py - creates the demo dataset for this project.

All data here is GENERATED BY THIS SCRIPT with a fixed random seed. It is not
real patient data and not derived from any real dataset - it exists only so
the SQL analysis has something deterministic to run against.
"""
import sqlite3
from pathlib import Path

import pandas as pd
import numpy as np

DB = Path(__file__).parent / "clinic_demo.db"
SEED = 42


def generate():
    rng = np.random.default_rng(SEED)
    clinics = ["North Clinic", "South Clinic", "Riverside Clinic"]
    reasons = ["Check-up", "Blood test", "Vaccination", "Follow-up", "New symptom"]

    patients = pd.DataFrame({
        "patient_id": range(1, 201),
        "age_band": rng.choice(["18-34", "35-49", "50-64", "65+"], 200, p=[.25, .3, .25, .2]),
        "registered_clinic": rng.choice(clinics, 200),
    })

    n = 1200
    dates = pd.date_range("2026-01-01", "2026-06-30", freq="D")
    appointments = pd.DataFrame({
        "appointment_id": range(1, n + 1),
        "patient_id": rng.integers(1, 201, n),
        "clinic": rng.choice(clinics, n),
        "reason": rng.choice(reasons, n),
        "appointment_date": rng.choice(dates, n),
        "days_waited": rng.integers(0, 42, n),
        "attended": rng.choice([1, 0], n, p=[0.85, 0.15]),
    })
    appointments["appointment_date"] = appointments["appointment_date"].astype(str)
    return patients, appointments


def main():
    patients, appointments = generate()
    if DB.exists():
        DB.unlink()
    with sqlite3.connect(DB) as con:
        patients.to_sql("patients", con, index=False)
        appointments.to_sql("appointments", con, index=False)
    print(f"Wrote {DB} ({len(patients)} patients, {len(appointments)} appointments)")
    print("Reminder: every row is synthetic demo data created by generate_data.py (seed 42).")


if __name__ == "__main__":
    main()
